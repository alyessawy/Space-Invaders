void playNote(int note, int duration_ms) {
    if (note > 0) {
        buzzer.period_us(1000000 / note); 
        buzzer.write(0.5); 
        ThisThread::sleep_for(std::chrono::milliseconds(duration_ms));
        buzzer.write(0.0); 
    } else {
        ThisThread::sleep_for(std::chrono::milliseconds(duration_ms)); 
    }
}


