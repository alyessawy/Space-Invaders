void handle_difficulty_input() {
    Direction dir = joystick.get_direction();
    if (dir == N) {
        selected_difficulty = (Difficulty)((selected_difficulty - 1 + 3) % 3);
        ThisThread::sleep_for(200ms);
    } else if (dir == S) {
        selected_difficulty = (Difficulty)((selected_difficulty + 1) % 3);
        ThisThread::sleep_for(200ms);
    }
    if (button1.read() == 1 || dir == E) {
        current_state = PLAYING;
        aliens.init(3, 5);
        aliens.set_difficulty((int)selected_difficulty);
        score = 0;
        lives = (selected_difficulty == EASY) ? 3 : (selected_difficulty == MEDIUM) ? 2 : 1;
        segDisplay.write(HEX_DISPLAY[lives]);
        missile_count = (selected_difficulty == EASY) ? 3 : (selected_difficulty == MEDIUM) ? 1 : 0;
        ThisThread::sleep_for(200ms);
    }
}


void game_loop() {
    lcd.clear();
    
    
    UserInput input = {joystick.get_direction()};
    player.update(input);
    
    aliens.update();
    aliens.fire_laser(alien_lasers, MAX_ALIEN_LASERS);
    aliens.update_lasers(alien_lasers, MAX_ALIEN_LASERS);
    if (button1.read() == 1 && !laser.is_active()) {
        Position2D pos = player.get_pos();
        laser.fire(pos.x + player.get_width()/2, pos.y);
        for (int i = 0; i < 2; i++) {
            playNote(laser_notes[i], laser_durations[i]);
        }
        ThisThread::sleep_for(100ms);
    }
    
    // Fire missile
    if (button2.read() == 1 && !missile.is_active() && missile_count > 0) {
        Position2D pos = player.get_pos();
        missile.fire(pos.x + player.get_width()/2 - missile.get_width()/2, pos.y);
       for (int i = 0; i < 3; i++) {
            playNote(missile_notes[i], missile_durations[i]);
        }

 missile_count--;
        ThisThread::sleep_for(100ms);
    }
    
    // Update laser
    if (laser.is_active()) {
        laser.update();
        
        int hit_alien_index = aliens.check_collision(
            laser.get_x(), 
            laser.get_y(), 
            laser.get_width(), 
            laser.get_height()
        );
        
        if (hit_alien_index != -1) {
            score += aliens.get_points_for_alien(hit_alien_index);
            aliens.remove_alien(hit_alien_index);
            laser.init(0, 0);
            
            if (aliens.get_alien_count() == 0) {
                aliens.init(3, 5);
                aliens.set_difficulty((int)selected_difficulty);
                missile_count = (selected_difficulty == EASY) ? 3 : (selected_difficulty == MEDIUM) ? 1 : 0;
            }
        }
    }
    
    // Update missile
    if (missile.is_active()) {
        missile.update();
        
        int aliens_hit = aliens.check_missile_collision(
            missile.get_x(), 
            missile.get_y(), 
            missile.get_width(), 
            missile.get_height()
        );
        
        if (aliens_hit > 0) {
            score += aliens_hit * 20;
            missile.init(0, 0);
            
            if (aliens.get_alien_count() == 0) {
                aliens.init(3, 5);
                aliens.set_difficulty((int)selected_difficulty);
                missile_count = (selected_difficulty == EASY) ? 3 : (selected_difficulty == MEDIUM) ? 1 : 0;
            }
        }
    }
    
    // Check for alien laser collisions with player
    for (int i = 0; i < MAX_ALIEN_LASERS; i++) {
        if (alien_lasers[i].is_active()) {
            Position2D player_pos = player.get_pos();
            if (alien_lasers[i].get_x() < player_pos.x + player.get_width() &&
                alien_lasers[i].get_x() + alien_lasers[i].get_width() > player_pos.x &&
                alien_lasers[i].get_y() < player_pos.y + player.get_height() &&
                alien_lasers[i].get_y() + alien_lasers[i].get_height() > player_pos.y) {
                lives--;
                alien_lasers[i].init(0, 0);
                if (lives <= 0) {
                    current_state = GAME_OVER;
                } else {
                    player.init(38, 40);
                    laser.init(0, 0);
                    missile.init(0, 0);
                }
            }
        }
    }
    
    // Check for aliencollisions with player
    Position2D player_pos = player.get_pos();
    if (aliens.check_spaceship_collision(
        player_pos.x, 
        player_pos.y, 
        player.get_width(), 
        player.get_height()
    )) {
        lives--;
        if (lives <= 0) {
            current_state = GAME_OVER;
        } else {
            player.init(38, 40);
            laser.init(0, 0);
            missile.init(0, 0);
            aliens.init(3, 5);
            aliens.set_difficulty((int)selected_difficulty);
        }
    }
    
    // Check if aliens reached bottom 
    if (aliens.alien_at_bottom(player.get_pos().y)) {
        lives--;
        if (lives <= 0) {
            current_state = GAME_OVER;
        } else {
            player.init(38, 40);
            laser.init(0, 0);
            missile.init(0, 0);
            aliens.init(3, 5);
            aliens.set_difficulty((int)selected_difficulty);
        }
    }
    
    
    player.draw(lcd);
    laser.draw(lcd);
    missile.draw(lcd);
    aliens.draw(lcd);
    for (int i = 0; i < MAX_ALIEN_LASERS; i++) {
        alien_lasers[i].draw(lcd);
    }
    segDisplay.write(HEX_DISPLAY[lives]);
    lcd.refresh();
    
    
    if (buttonA.read() == 0) {
        current_state = SPLASH;
        ThisThread::sleep_for(200ms);
    }
}

void show_game_over() {
    for (int i = 0; i < 4; i++) {
        playNote(gameover_notes[i], gameover_durations[i]);
    }
    lcd.clear();
    
    lcd.drawSprite(28, 2, 22, 27, (uint32_t*)game_over_sprite);
    char score_str[12];
    sprintf(score_str, "Score: %04d", score);
    lcd.printString(score_str, 12, 4);
    lcd.printString("Press button 1", 0, 5);
    segDisplay.write(HEX_DISPLAY[0]);
    lcd.refresh();
    
    if (buttonA.read() == 0 || button1.read() == 1) {
        current_state = SPLASH;
        ThisThread::sleep_for(200ms);
    }
}

int main() {
    init();
    while(1) {
        switch(current_state) {
            case SPLASH:
                show_splash();
                if (button1.read() == 1 || joystick.get_mag() > 0.1) {
                    current_state = DIFFICULTY;
                    ThisThread::sleep_for(200ms);
                }
                break;
            case DIFFICULTY:
                show_difficulty_menu();
                handle_difficulty_input();
                break;
            case PLAYING:
                game_loop();
                break;
            case GAME_OVER:
                show_game_over();
                break;
        }
        ThisThread::sleep_for(50ms);
    }
}