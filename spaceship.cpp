Spaceship::Spaceship() : _x(0), _y(0), _speed(2) {}

void Spaceship::init(int start_x, int start_y) {
    _x = start_x;
    _y = start_y;
    _speed = 2;  
}

void Spaceship::draw(N5110 &lcd) {
    lcd.drawSprite(_x, _y, _height, _width, (uint32_t *)_sprite);
}

void Spaceship::update(UserInput input) {
    
    if (input.d == E) { 
        _x += _speed;
    } else if (input.d == W) {
        _x -= _speed;
    }

    
    if (_x < 0) { _x = 0; }
    if (_x > WIDTH - _width) { _x = WIDTH - _width; }
}

Position2D Spaceship::get_pos() { 
    return {_x, _y}; 
}

const uint32_t* Spaceship::get_sprite() const { 
    return _sprite; 
}

int Spaceship::get_width() const { 
    return _width; 
}

int Spaceship::get_height() const { 
    return _height; 
}